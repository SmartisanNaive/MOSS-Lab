/** Build a complete MOSS wheel from the production closure and verified native tools. */
import { cp, mkdir, mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { spawnSync } from 'node:child_process'
import { dirname, join, resolve } from 'node:path'
import { tmpdir } from 'node:os'
import { fileURLToPath } from 'node:url'
import extractZip from 'extract-zip'
import { extract as extractTar } from 'tar'
import { materializeStagedLinks, deduplicateStagedWorkspacePackages } from './build-exe-for-python-sdk-staging.ts'
import { restoreLegacyHoists, pnpmInvocation } from './executable-packaging.ts'
import { downloadPrimaryRuntimeAsset } from './primary-runtime/prepare.ts'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const args = process.argv.slice(2)
const value = name => { const index = args.indexOf(name); return index < 0 ? undefined : args[index + 1] }
const python = value('--python') || (process.platform === 'win32' ? 'python' : 'python3')
const output = resolve(value('--output') || join(root, 'dist-moss'))
const staging = resolve(root, '.moss-build/application')
const app = join(staging, 'app')
const platform = process.platform === 'win32' ? 'win' : process.platform === 'darwin' ? 'macos' : process.platform
const target = `${platform}-${process.arch}`
const tag = { 'win-x64': 'win_amd64', 'macos-arm64': 'macosx_14_0_arm64', 'linux-x64': 'manylinux_2_28_x86_64' }[target]
if (!tag) throw new Error(`Unsupported MOSS build host: ${target}`)

function run(command, parameters, cwd = root) {
  const result = spawnSync(command, parameters, { cwd, stdio: 'inherit', env: process.env })
  if (result.error) throw result.error
  if (result.status !== 0 || result.signal) throw new Error(`MOSS build command failed: ${command} (${result.status ?? result.signal})`)
}
function pnpm(parameters) { const [command, args] = pnpmInvocation(parameters); run(command, args) }

await rm(staging, { recursive: true, force: true })
await mkdir(dirname(staging), { recursive: true })
try {
  pnpm(['--filter', 'dsh-python-runtime-closure', 'deploy', '--legacy', '--prod',
    '--config.allow-unused-patches=true', '--config.node-linker=hoisted',
    '--config.auto-install-peers=false', '--config.link-workspace-packages=true', '--config.hoist-workspace-packages=false', app])
} finally {
  pnpm(['install', '--offline', '--frozen-lockfile', '--prod=false', '--ignore-scripts'])
}
await restoreLegacyHoists(app, join(root, 'python/sdk-runtime/node_modules'))
await materializeStagedLinks(app)
await deduplicateStagedWorkspacePackages(app, root)
for (const name of await readdir(app)) {
  if (!['node_modules', 'package.json'].includes(name)) await rm(join(app, name), { recursive: true, force: true })
}
for (const name of ['moss-start.mjs', 'moss-model.patch.yml', 'labscriptai-ot.lock.json', 'LICENSE', 'THIRD-PARTY-NOTICES']) {
  // The notice file is generated by the existing build when present.
  try { await cp(join(root, name), join(app, name)) } catch (error) {
    if (name !== 'THIRD-PARTY-NOTICES' || error.code !== 'ENOENT') throw error
  }
}
await cp(join(root, 'python/moss-runtime/managed-start.mjs'), join(app, 'managed-start.mjs'))
for (const directory of ['internal/experiment', 'internal/xiaozhi']) {
  await cp(join(root, directory), join(app, directory), { recursive: true,
    filter: path => !path.endsWith('.test.mjs') && !path.split(/[\\/]/).includes('tests') })
}
await cp(join(root, 'internal/chat-tools.mjs'), join(app, 'internal/chat-tools.mjs'))
await mkdir(join(app, 'scripts'), { recursive: true })
await cp(join(root, 'scripts/labscriptai-runtime.mjs'), join(app, 'scripts/labscriptai-runtime.mjs'))

const lock = JSON.parse(await readFile(join(root, 'scripts/primary-runtime/lock.json'), 'utf8'))
const artifact = lock.targets[target.replace('macos-', 'mac-')]
const filename = `node-v${lock.nodeVersion}-${artifact.nodeArchive}`
const archive = await downloadPrimaryRuntimeAsset(`https://nodejs.org/dist/v${lock.nodeVersion}/${filename}`, artifact.nodeSha256,
  join(root, '.moss-build/downloads'))
const nodeStage = await mkdtemp(join(tmpdir(), 'moss-node-'))
try {
  if (process.platform === 'win32') await extractZip(archive, { dir: nodeStage })
  else await extractTar({ file: archive, cwd: nodeStage })
  const source = join(nodeStage, filename.replace(/\.(zip|tar\.gz)$/, ''))
  await cp(source, join(staging, 'node'), { recursive: true, dereference: true })
  if (process.platform !== 'win32') {
    for (const name of ['npm', 'npx']) {
      await writeFile(join(staging, 'node/bin', name),
        `#!/usr/bin/env node\nrequire('../lib/node_modules/npm/bin/${name}-cli.js')\n`, { mode: 0o755 })
    }
  }
} finally { await rm(nodeStage, { recursive: true, force: true }) }

// The uv wheel supplies the same reviewed version and preserves its licenses.
const tools = join(staging, 'tools')
const uvCache = join(root, '.moss-build/uv')
await mkdir(uvCache, { recursive: true })
run(python, ['-m', 'pip', 'download', '--no-deps', '--only-binary=:all:', '--dest', uvCache, 'uv==0.11.23'])
const uvWheel = (await readdir(uvCache)).find(name => name.startsWith('uv-0.11.23-') && name.endsWith('.whl'))
if (!uvWheel) throw new Error('The native uv wheel is missing')
await mkdir(tools, { recursive: true })
run(python, ['-c', `import sys,zipfile,pathlib,os
root=pathlib.Path(sys.argv[2])
with zipfile.ZipFile(sys.argv[1]) as z:
 entries=[n for n in z.namelist() if n.endswith(('/uv.exe','/uv'))]
 assert len(entries)==1, entries
 target=root/('uv.exe' if os.name=='nt' else 'uv')
 target.write_bytes(z.read(entries[0]));target.chmod(0o755)
 for name in z.namelist():
  if '/licenses/' in name and not name.endswith('/'):
   destination=root/'licenses'/pathlib.Path(name).name;destination.parent.mkdir(exist_ok=True);destination.write_bytes(z.read(name))
`, join(uvCache, uvWheel), tools])
run(join(tools, process.platform === 'win32' ? 'uv.exe' : 'uv'), ['--version'])

const packageRoot = join(root, 'python/moss-lab')
const payload = join(packageRoot, 'src/moss_lab/_payload')
await mkdir(payload, { recursive: true })
run(python, ['-c', `import pathlib,zipfile,sys
root=pathlib.Path(sys.argv[1])
with zipfile.ZipFile(sys.argv[2],'w',compression=zipfile.ZIP_DEFLATED,compresslevel=6) as z:
 for p in sorted(root.rglob('*')):
  if p.is_symlink():raise RuntimeError('Application contains a link: '+str(p))
  if p.is_file():z.write(p,p.relative_to(root).as_posix())
`, staging, join(payload, 'application.zip')])
const version = JSON.parse(await readFile(join(root, 'python/moss-runtime/package.json'), 'utf8')).version
const revision = spawnSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' })
if (revision.status !== 0) throw new Error('Source revision is unavailable')
const checksum = createHash('sha256').update(await readFile(join(payload, 'application.zip'))).digest('hex')
await writeFile(join(payload, 'manifest.json'), JSON.stringify({ schema: 1, manager_api: 1, version, revision: revision.stdout.trim(),
  platform: process.platform, wheel_platform: tag, sha256: checksum,
  node: process.platform === 'win32' ? 'node/node.exe' : 'node/bin/node', entry: 'app/managed-start.mjs' }, null, 2) + '\n')
await mkdir(output, { recursive: true })
run(python, ['-m', 'pip', 'wheel', '--no-deps', '--wheel-dir', output, packageRoot])
const wheel = `moss_lab-${version}-py3-none-${tag}.whl`
const wheelHash = createHash('sha256').update(await readFile(join(output, wheel))).digest('hex')
await writeFile(join(output, 'moss-windows.json'), JSON.stringify({ schema: 1, version, revision: revision.stdout.trim(), wheel, sha256: wheelHash }, null, 2) + '\n')
console.log(`MOSS wheel ready: ${join(output, wheel)}`)
